CREATE TABLE token_quota_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope VARCHAR(32) NOT NULL CHECK (scope IN ('MODEL_GROUP', 'API_KEY')),
    target_id BIGINT NOT NULL,
    model VARCHAR(256) NOT NULL DEFAULT '',
    period VARCHAR(16) NOT NULL CHECK (period IN ('DAY', 'WEEK', 'MONTH', 'LIFETIME')),
    limit_tokens NUMERIC(24, 6) NOT NULL CHECK (limit_tokens > 0),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE(scope, target_id, model, period)
);

-- Preserve existing budgets, including per-model daily rules and legacy lifetime key budgets.
INSERT INTO token_quota_rules(scope, target_id, model, period, limit_tokens)
SELECT 'MODEL_GROUP', g.id, entry.key, 'DAY', entry.value::numeric
FROM model_groups g CROSS JOIN LATERAL jsonb_each_text(g.model_daily_limits::jsonb) entry
WHERE NOT g.deleted AND entry.value::numeric > 0;
INSERT INTO token_quota_rules(scope, target_id, period, limit_tokens)
SELECT 'API_KEY', id, 'LIFETIME', token_limit FROM api_credentials WHERE NOT deleted AND token_limit > 0;
UPDATE model_groups SET model_daily_limits = '{}';
UPDATE api_credentials SET token_limit = 0;

-- Attribute usage to the group at admission: moving/deleting a key must not erase shared usage.
ALTER TABLE usage_records ADD COLUMN model_group_id BIGINT REFERENCES model_groups(id);
UPDATE usage_records r SET model_group_id = c.model_group_id FROM api_credentials c WHERE c.id = r.api_credential_id;
CREATE INDEX idx_usage_records_group_time ON usage_records(model_group_id, started_at);
CREATE INDEX idx_usage_records_key_time ON usage_records(api_credential_id, started_at);
